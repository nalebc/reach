// Reach's browser extension (browser-extension/, docs/parity/G-browser-tools.md):
// writes its page interpreter from the server's own (server/tool-page-runtime.mjs),
// so the one function that runs in pages is the same on a Mac and in the
// extension; with --package, the store upload: a zip without the repo
// build's fixed "key" (the stores assign their own id).
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { toolPageOperation } from "../server/tool-page-runtime.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const extensionDir = path.join(root, "browser-extension");
export const runtimeFile = path.join(extensionDir, "page-runtime.js");
// What a store package holds: nothing else in the folder ships.
export const PACKAGE_FILES = ["manifest.json", "service-worker.js", "reach-extension.js", "page-runtime.js",
  "icons/reach-16.png", "icons/reach-32.png", "icons/reach-48.png", "icons/reach-128.png"];

export function pageRuntimeSource() {
  return [
    "// Generated by scripts/build-browser-extension.mjs from server/tool-page-runtime.mjs.",
    "// Do not edit: the same fixed interpreter runs in pages on a Mac (Apple Events)",
    "// and here (chrome.scripting, isolated world). Definitions carry data, never code.",
    `globalThis.toolPageOperation = ${toolPageOperation.toString()};`,
    "",
  ].join("\n");
}

export function storeManifest(text = fs.readFileSync(path.join(extensionDir, "manifest.json"), "utf8")) {
  const manifest = JSON.parse(text);
  delete manifest.key;
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (bytes) => {
  let c = 0xffffffff;
  for (const byte of bytes) c = CRC[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
// A plain zip (deflate, fixed 1980 date so the same input gives the same bytes).
export function zip(entries) {
  const locals = [], centrals = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const nameBytes = Buffer.from(name, "utf8");
    const packed = zlib.deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6); local.writeUInt16LE(8, 8);
    local.writeUInt16LE(0, 10); local.writeUInt16LE(0x21, 12); local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(packed.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(nameBytes.length, 26); local.writeUInt16LE(0, 28);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10); central.writeUInt16LE(0, 12); central.writeUInt16LE(0x21, 14); central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(packed.length, 20); central.writeUInt32LE(data.length, 24); central.writeUInt16LE(nameBytes.length, 28);
    central.writeUInt32LE(offset, 42);
    locals.push(local, nameBytes, packed);
    centrals.push(central, nameBytes);
    offset += 30 + nameBytes.length + packed.length;
  }
  const directory = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}

export function storePackage() {
  return zip(PACKAGE_FILES.map((name) => ({
    name,
    data: name === "manifest.json" ? Buffer.from(storeManifest(), "utf8")
      : name === "page-runtime.js" ? Buffer.from(pageRuntimeSource(), "utf8")
      : fs.readFileSync(path.join(extensionDir, name)),
  })));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(runtimeFile, pageRuntimeSource());
  if (process.argv.includes("--package")) {
    const { version } = JSON.parse(fs.readFileSync(path.join(extensionDir, "manifest.json"), "utf8"));
    const out = path.join(root, "dist-extension", `reach-browser-extension-${version}.zip`);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, storePackage());
    console.log(out);
  }
}
