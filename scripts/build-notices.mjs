// License texts for dependencies bundled into the browser and agent downloads.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const env = { ...process.env, GOOS: "js", GOARCH: "wasm", GOTOOLCHAIN: "auto" };
const go = (args) => execFileSync("go", args, { cwd: path.join(root, "tailnet"), env, encoding: "utf8", maxBuffer: 64 << 20, timeout: 120000 });
const sections = [];
function license(name, directory) {
  const files = fs.readdirSync(directory).filter(f => /^(LICENSE|COPYING|NOTICE|COPYRIGHT)(?:$|[._-])/i.test(f) && fs.statSync(path.join(directory, f)).isFile()).sort();
  if (!files.length) throw Error(`No license text found for ${name}. Review before distributing.`);
  sections.push(`## ${name}\n\n` + files.map(file => `### ${file}\n\n\`\`\`text\n${fs.readFileSync(path.join(directory, file), "utf8").replace(/[ \t]+$/gm, "").trim()}\n\`\`\`\n`).join("\n"));
}
for (const name of ["react", "react-dom", "scheduler", "lucide-react", "@xterm/xterm", "@xterm/addon-fit", "@capacitor/core", "@capacitor/app", "@capacitor/filesystem", "@capacitor/share", "ws", "json5", "pdfjs-dist"]) {
  const directory = path.join(root, "node_modules", name);
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, "package.json"), "utf8"));
  license(`${name} ${pkg.version}`, directory);
}
// Markdown's parser is composed of small packages; include their runtime
// licenses along with the file viewer's syntax highlighter.
const fileViewerPackages = new Set();
function fileViewerLicense(name) {
  if (name.startsWith("@types/") || name === "react" || fileViewerPackages.has(name)) return;
  fileViewerPackages.add(name);
  const directory = path.join(root, "node_modules", name);
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, "package.json"), "utf8"));
  license(`${name} ${pkg.version}`, directory);
  for (const dependency of Object.keys(pkg.dependencies || {}).sort()) fileViewerLicense(dependency);
}
for (const name of ["highlight.js", "react-markdown", "remark-gfm"]) fileViewerLicense(name);
for (const directory of ["cmaps", "standard_fonts", "wasm"])
  license(`PDF.js ${directory} assets`, path.join(root, "node_modules/pdfjs-dist", directory));
// go list emits successive JSON objects. Package records end at a column-zero brace.
const modules = new Map();
for (const record of go(["list", "-deps", "-json", "."]).trim().split(/\n(?=\{)/)) {
  const module = JSON.parse(record).Module;
  if (module?.Dir && !module.Main) modules.set(module.Path, module);
}
for (const [name, module] of [...modules].sort(([a], [b]) => a.localeCompare(b))) license(`${name} ${module.Version}`, module.Dir);
license(`Go runtime (${go(["env", "GOVERSION"]).trim()})`, go(["env", "GOROOT"]).trim());
const header = `# Third-party notices\n\nGenerated by \`node scripts/build-notices.mjs\` from the installed dependencies and the Go modules linked into the browser client. Regenerate when updating dependencies. Reach's MIT license does not replace these notices. Runtime npm dependencies also ship their own license files. OpenClaw-derived source and artwork retain their notices in \`server/openclaw-LICENSE.txt\`, which ships with the package. Product names and logos identify integrations; no endorsement is implied.\n\n`;
fs.writeFileSync(path.join(root, "docs/THIRD_PARTY_NOTICES.md"), header + sections.join("\n"));
console.log(`Collected bundled dependency notices (${sections.length} components).`);
