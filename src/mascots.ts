// Which face: the one the computer drew for it when it was invited
// (server/mascots.mjs: no two alike while both are listed). One invited
// before mascots, until the computer gives it one: a pick from its id, the
// same on every phone. FNV-1a, 32 bits.
export function mascotIndex(id: string) {
  let h = 0x811c9dc5;
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0) % MASCOTS.length;
}

export const mascotFor = (id: string, drawn?: number) =>
  MASCOTS[Number.isInteger(drawn) && drawn! >= 0 && drawn! < MASCOTS.length ? drawn! : mascotIndex(id)];

// One rect per run of the same color in a row: a face is ~60 rects, not 256.
export type MascotRect = { x: number; y: number; w: number; fill: string };
const runs = new Map<Mascot, MascotRect[]>();
export function mascotRects(mascot: Mascot) {
  const hit = runs.get(mascot);
  if (hit) return hit;
  const rects: MascotRect[] = [];
  mascot.art.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const key = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === key) end++;
      const fill = mascot.colors[key];
      if (key !== "." && fill) rects.push({ x, y, w: end - x, fill });
      x = end;
    }
  });
  runs.set(mascot, rects);
  return rects;
}
